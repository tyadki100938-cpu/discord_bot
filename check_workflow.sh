#!/bin/bash

# 1. 直近のワークフロー実行状況を綺麗にリスト表示 (最新5件)
echo "=================================================="
echo " 🔄 GitHub Actions 最新の実行ステータス (直近5件)"
echo "=================================================="
gh run list --limit 5

# 2. 一番最新のワークフローIDを自動で取得
LATEST_RUN_ID=$(gh run list --limit 1 --json databaseId --jq '.[0].databaseId')

if [ -z "$LATEST_RUN_ID" ]; then
    echo "❌ ワークフローの実行履歴が見つかりませんでした。"
    exit 1
fi

echo -e "\n=================================================="
echo " 🔍 最新ワークフロー (ID: $LATEST_RUN_ID) の詳細状況"
echo "=================================================="
# 進行状況をリアルタイムに表示したい場合は gh run watch $LATEST_RUN_ID も便利です
gh run view $LATEST_RUN_ID

# 3. ユーザーにログを表示するか確認
echo -e "\n--------------------------------------------------"
read -p "❓ 最新ワークフローの実行ログを表示しますか？ (y/N): " ANSWER

if [[ "$ANSWER" =~ ^[Yy]$ ]]; then
    echo -e "\n=================================================="
    echo " 📋 最新の実行ログ"
    echo "=================================================="
    # ログが長い場合に備えて less でスクロールできるようにしています（qで終了）
    gh run view $LATEST_RUN_ID --log | less -R
else
    echo "👋 ログの表示をスキップしました。"
fi
